/* Production browser test for the Aurora account workspace.
   Screenshots are generated by real Chromium. No wallet or payments needed. */
const assert = require("node:assert/strict");
const fs = require("node:fs");
const { spawn } = require("node:child_process");
const { setTimeout: delay } = require("node:timers/promises");
const { chromium } = require("playwright");

async function waitForServer(base, process, getOutput) {
  for (let i = 0; i < 45; i++) {
    if (process.exitCode !== null) break;
    try {
      const response = await fetch(base + "/api/health", { signal: AbortSignal.timeout(1000) });
      if (response.ok) return;
    } catch {}
    await delay(1000);
  }
  throw new Error("Server failed to start: " + getOutput());
}

async function main() {
  const port = 3497;
  const origin = "http://127.0.0.1:" + port;
  const process = spawn("node", ["node_modules/next/dist/bin/next", "start", "-p", String(port), "-H", "127.0.0.1"], {
    env: { ...global.process.env, NODE_ENV: "production" },
    stdio: ["ignore", "pipe", "pipe"],
  });
  let output = "";
  for (const stream of [process.stdout, process.stderr]) {
    stream.on("data", part => { output = (output + String(part)).slice(-2500); });
  }
  let browser;
  try {
    await waitForServer(origin, process, () => output);
    browser = await chromium.launch({ headless: true, args: ["--no-sandbox"] });
    const outDir = "/tmp/scn-aurora-panel";
    fs.mkdirSync(outDir, { recursive: true });

    const desktop = await browser.newPage({ viewport: { width: 1440, height: 900 }, deviceScaleFactor: 1 });
    await desktop.goto(origin + "/dashboard", { waitUntil: "domcontentloaded", timeout: 30000 });
    await desktop.locator(".scn-dashboard-hero h1").waitFor({ state: "visible", timeout: 25000 });
    assert((await desktop.locator(".scn-dashboard-hero h1").innerText()).includes("Your network."));
    assert(await desktop.locator("aside.scn-app-sidebar").isVisible());
    assert(await desktop.locator(".scn-quick-card").count() === 4);
    const actualBg = await desktop.locator(".scn-app").evaluate(el => getComputedStyle(el).backgroundColor);
    assert.notEqual(actualBg, "rgb(0, 0, 0)");
    await desktop.screenshot({ path: outDir + "/desktop-dashboard.png", fullPage: true, animations: "disabled" });
    console.log("PASS desktop Aurora dashboard: hero, actions and sidebar");

    await desktop.goto(origin + "/user", { waitUntil: "domcontentloaded", timeout: 30000 });
    await desktop.locator(".scn-user-search-card").waitFor({ state: "visible", timeout: 25000 });
    await desktop.locator(".scn-dashboard-hero").waitFor({ state: "visible" });
    await desktop.screenshot({ path: outDir + "/desktop-user.png", fullPage: true, animations: "disabled" });
    console.log("PASS desktop personal wallet dashboard");

    const mobile = await browser.newPage({ viewport: { width: 390, height: 844 }, deviceScaleFactor: 1, isMobile: true, hasTouch: true });
    await mobile.goto(origin + "/dashboard", { waitUntil: "domcontentloaded", timeout: 30000 });
    await mobile.locator(".scn-dashboard-hero h1").waitFor({ state: "visible", timeout: 25000 });
    const menu = mobile.getByRole("button", { name: "Toggle navigation" });
    await menu.waitFor({ state: "visible" });
    await menu.click();
    assert.equal(await menu.getAttribute("aria-expanded"), "true");
    await mobile.locator("#scn-app-mobile-navigation a[href='/user']").click();
    await mobile.locator(".scn-user-search-card").waitFor({ state: "visible", timeout: 25000 });
    await mobile.getByRole("button", { name: "Toggle language" }).click();
    await mobile.locator(".scn-dashboard-hero h1").waitFor({ state: "visible" });
    assert((await mobile.locator(".scn-dashboard-hero h1").innerText()).includes("کنترل حساب"));
    const overflow = await mobile.evaluate(() => ({
      scroll: document.documentElement.scrollWidth,
      width: document.documentElement.clientWidth,
    }));
    assert(overflow.scroll <= overflow.width + 2, "Mobile horizontal overflow: " + JSON.stringify(overflow));
    await mobile.evaluate(() => window.scrollTo(0,0));
    await mobile.screenshot({ path: outDir + "/mobile-user-fa.png", fullPage: true, animations: "disabled" });
    console.log("PASS mobile Aurora user panel: drawer, RTL locale and no horizontal overflow");

    await mobile.goto(origin + "/dashboard", { waitUntil: "domcontentloaded", timeout: 30000 });
    await mobile.locator(".scn-dashboard-hero h1").waitFor({ state: "visible" });
    await mobile.evaluate(() => window.scrollTo(0,0));
    await mobile.screenshot({ path: outDir + "/mobile-dashboard-fa.png", fullPage: true, animations: "disabled" });
    console.log("PASS Aurora dashboard mobile screenshot");
  } finally {
    if (browser) await browser.close();
    process.kill("SIGTERM");
  }
}

main().catch(error => { console.error(error); global.process.exitCode = 1; });
